#!/usr/bin/env python3
"""
Rank raw menu extractions by a simple quality score.
Writes bench/results/extraction_ranking.csv and notes/extraction_ranking.md
"""
from __future__ import annotations

import argparse
import csv
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}


def log(msg: str) -> None:
    print(f"[rank] {msg}", file=sys.stderr, flush=True)


def list_images(input_dir: Path) -> list[Path]:
    return sorted(
        p for p in input_dir.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_EXTS
    )


def score_menu(menu_id: str, path: Path, source_fallback: str) -> dict:
    d = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    items = d.get("items") or []
    confs: list[float] = []
    no_price = 0
    unknown_cur = 0
    low_conf = 0
    tags = {"chicken": 0, "vegetable": 0, "beer": 0}
    for it in items:
        try:
            c = float(it["confidence"]) if it.get("confidence") is not None else None
        except (TypeError, ValueError):
            c = None
        if c is not None:
            confs.append(c)
            if c < 0.75:
                low_conf += 1
        if it.get("price_value") is None and not it.get("price_raw"):
            no_price += 1
        cur = (it.get("currency") or "unknown").upper()
        if cur not in ("USD", "KHR"):
            unknown_cur += 1
        for t in it.get("tags") or []:
            if t in tags:
                tags[t] += 1

    n = len(items)
    avg_conf = statistics.mean(confs) if confs else 0.0
    quality = (
        avg_conf
        - 0.15 * (unknown_cur / n if n else 1.0)
        - 0.15 * (no_price / n if n else 1.0)
        - 0.1 * (low_conf / n if n else 1.0)
        + min(n, 40) / 200.0
    )
    return {
        "menu_id": menu_id,
        "source_file": d.get("_source_file") or source_fallback,
        "restaurant": d.get("restaurant_name_en")
        or d.get("restaurant_name_raw")
        or menu_id,
        "items": n,
        "avg_confidence": round(avg_conf, 3),
        "low_conf_lt_0_75": low_conf,
        "unknown_currency": unknown_cur,
        "missing_price": no_price,
        "chicken": tags["chicken"],
        "vegetable": tags["vegetable"],
        "beer": tags["beer"],
        "quality_score": round(quality, 3),
        "finish_reason": "n/a",
        "truncated": False,
    }


def attach_finish(raw_dir: Path, row: dict) -> None:
    rp = raw_dir / f"{row['menu_id']}.raw_response.json"
    if not rp.exists():
        return
    try:
        resp = json.loads(rp.read_text(encoding="utf-8"))
        fr = (resp.get("choices") or [{}])[0].get("finish_reason")
        row["finish_reason"] = fr or "?"
        row["truncated"] = fr == "length"
    except Exception as e:
        log(f"raw_response parse skip {row['menu_id']}: {e}")
        row["finish_reason"] = "?"
        row["truncated"] = False


def write_md(ranked: list[dict], out: Path, model_slug: str) -> None:
    total_items = sum(r["items"] for r in ranked)
    truncated = [r for r in ranked if r["truncated"]]
    with_chicken = sum(1 for r in ranked if r["chicken"])
    with_veg = sum(1 for r in ranked if r["vegetable"])
    with_beer = sum(1 for r in ranked if r["beer"])

    lines = [
        "# Extraction ranking (full dataset)",
        "",
        f"**Model:** `{model_slug.replace('__', '/')}`  ",
        f"**Menus ranked:** {len(ranked)}  ",
        f"**Total items:** {total_items}  ",
        f"**Generated by:** `scripts/rank_extractions.py`  ",
        f"**Machine CSV:** `bench/results/extraction_ranking.csv`",
        "",
        "## Quality score",
        "",
        "```",
        "quality ≈ avg_confidence",
        "         - 0.15 * (unknown_currency / items)",
        "         - 0.15 * (missing_price / items)",
        "         - 0.10 * (low_conf / items)",
        "         + min(items, 40) / 200",
        "```",
        "",
        "Higher is better. This ranks **extraction health**, not restaurant food quality.",
        "Recommender ranking (verified → confidence → price) is separate — see HANDOVER §10.",
        "",
        "## Summary",
        "",
        f"- Truncated responses (`finish_reason=length`): **{len(truncated)}**"
        + (f" — {', '.join(r['menu_id'] for r in truncated)}" if truncated else ""),
        f"- Menus with chicken / vegetable / beer tags: **{with_chicken} / {with_veg} / {with_beer}**",
        f"- Beer coverage is thin in this extract set (only {with_beer} menu(s) tagged beer).",
        "",
        "## Ranked table (best → worst)",
        "",
        "| Rank | Menu | Quality | Items | Avg conf | Low conf | Unk $ | Chick | Veg | Beer | Trunc | Restaurant |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|:---:|---|",
    ]
    for i, r in enumerate(ranked, 1):
        rest = str(r["restaurant"]).replace("|", "/")[:40]
        lines.append(
            f"| {i} | `{r['menu_id']}` | {r['quality_score']:.3f} | {r['items']} | "
            f"{r['avg_confidence']:.3f} | {r['low_conf_lt_0_75']} | {r['unknown_currency']} | "
            f"{r['chicken']} | {r['vegetable']} | {r['beer']} | "
            f"{'yes' if r['truncated'] else ''} | {rest} |"
        )

    lines += [
        "",
        "## Lowest quality (review first)",
        "",
    ]
    for r in ranked[-5:]:
        reasons = []
        if r["truncated"]:
            reasons.append("truncated")
        if r["avg_confidence"] < 0.75:
            reasons.append("low avg confidence")
        if r["unknown_currency"]:
            reasons.append(f"{r['unknown_currency']} unknown currency")
        if r["items"] < 8:
            reasons.append("few items")
        if not reasons:
            reasons.append("relatively weaker score")
        lines.append(
            f"- **`{r['menu_id']}`** (score {r['quality_score']:.3f}): "
            + "; ".join(reasons)
        )

    lines += [
        "",
        "## Related",
        "",
        "- Model bake-off (sample): [`notes/bakeoff_sample.md`](bakeoff_sample.md)",
        "- Raw outputs: `raw/<model>/menu_*.json`",
        "- Re-run: `python3 scripts/rank_extractions.py --input-dir data-sets`",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    log(f"wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input-dir", type=Path, default=ROOT / "data-sets")
    ap.add_argument(
        "--raw-model-dir",
        type=Path,
        default=None,
        help="Default: winner from bench/results/winner.txt",
    )
    ap.add_argument(
        "--csv-out", type=Path, default=ROOT / "bench" / "results" / "extraction_ranking.csv"
    )
    ap.add_argument(
        "--md-out", type=Path, default=ROOT / "notes" / "extraction_ranking.md"
    )
    args = ap.parse_args()

    raw_dir = args.raw_model_dir
    if raw_dir is None:
        winner = ROOT / "bench" / "results" / "winner.txt"
        if winner.exists():
            slug = winner.read_text(encoding="utf-8").strip()
            raw_dir = ROOT / "raw" / slug
        else:
            cands = sorted(p for p in (ROOT / "raw").iterdir() if p.is_dir())
            if not cands:
                raise SystemExit("No raw model dir")
            raw_dir = cands[0]
    log(f"ranking {raw_dir}")

    images = list_images(args.input_dir)
    sample = "sample" in args.input_dir.name.lower()
    rows = []
    for i, img in enumerate(images, 1):
        mid = f"sample_{i:02d}" if sample else f"menu_{i:02d}"
        row = score_menu(mid, raw_dir / f"{mid}.json", img.name)
        attach_finish(raw_dir, row)
        rows.append(row)
        log(
            f"{mid} quality={row['quality_score']} items={row['items']} "
            f"conf={row['avg_confidence']} trunc={row['truncated']}"
        )

    ranked = sorted(rows, key=lambda r: (-r["quality_score"], -r["items"], r["menu_id"]))
    # add rank column
    for i, r in enumerate(ranked, 1):
        r["rank"] = i

    args.csv_out.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "rank",
        "menu_id",
        "quality_score",
        "items",
        "avg_confidence",
        "low_conf_lt_0_75",
        "unknown_currency",
        "missing_price",
        "chicken",
        "vegetable",
        "beer",
        "truncated",
        "finish_reason",
        "restaurant",
        "source_file",
    ]
    with args.csv_out.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(ranked)
    log(f"wrote {args.csv_out}")

    write_md(ranked, args.md_out, raw_dir.name)
    print(f"ranked {len(ranked)} menus -> {args.md_out}")


if __name__ == "__main__":
    main()
